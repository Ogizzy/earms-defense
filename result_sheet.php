<?php
// result_sheet.php?id=DEFENSE_ID — generate the official defense result sheet (PDF)
require_once __DIR__ . '/config/db.php';
require_once __DIR__ . '/config/actions.php';
require_can('view_results');
require_once __DIR__ . '/lib/fpdf.php';

$db = getDB();
$id = (int)($_GET['id'] ?? 0);
$d  = qrow($db, "SELECT d.*, pr.title, pr.department, u.name AS student_name, u.email AS student_email
                 FROM defenses d JOIN projects pr ON pr.id=d.project_id JOIN users u ON u.id=d.student_id
                 WHERE d.id=?", [$id]);
if (!$d) { http_response_code(404); echo 'Defense not found'; exit; }
if (!$d['finalized']) { http_response_code(409); echo 'Result is not finalized yet.'; exit; }

$scores = qrows($db, "SELECT s.*, u.name AS evaluator_name FROM defense_scores s JOIN users u ON u.id=s.evaluator_id
                      WHERE s.defense_id=? ORDER BY FIELD(s.evaluator_role,'supervisor','internal_examiner','external_examiner')", [$id]);

class ResultPDF extends FPDF {
    function Header() {
        $this->SetFont('Helvetica', 'B', 15);
        $this->Cell(0, 7, 'EARMS UNIVERSITY', 0, 1, 'C');
        $this->SetFont('Helvetica', '', 10);
        $this->Cell(0, 5, 'Electronic Academic Research Management System', 0, 1, 'C');
        $this->SetFont('Helvetica', 'B', 11);
        $this->SetTextColor(22, 163, 74);
        $this->Cell(0, 7, 'OFFICIAL DEFENSE RESULT SHEET', 0, 1, 'C');
        $this->SetTextColor(0, 0, 0);
        $this->SetDrawColor(22, 163, 74);
        $this->SetLineWidth(0.6);
        $this->Line(10, $this->GetY() + 1, 200, $this->GetY() + 1);
        $this->Ln(6);
    }
    function Footer() {
        $this->SetY(-18);
        $this->SetDrawColor(200, 200, 200);
        $this->SetLineWidth(0.2);
        $this->Line(10, $this->GetY(), 200, $this->GetY());
        $this->Ln(2);
        $this->SetFont('Helvetica', 'I', 7.5);
        $this->SetTextColor(120, 120, 120);
        $this->Cell(0, 4, 'Generated by EARMS Defense & Evaluation Service on ' . date('d M Y, H:i') . ' CAT', 0, 1, 'C');
        $this->Cell(0, 4, 'This is a system-generated document. Reference: ' . $this->ref, 0, 0, 'C');
    }
    public $ref = '';
}

$pdf = new ResultPDF();
$pdf->ref = $d['reference'];
$pdf->AliasNbPages();
$pdf->AddPage();

// ── Candidate / session block ──
$row = function($label, $value) use ($pdf) {
    $pdf->SetFont('Helvetica', 'B', 10);
    $pdf->Cell(45, 6.5, $label, 0, 0);
    $pdf->SetFont('Helvetica', '', 10);
    $pdf->MultiCell(0, 6.5, $value, 0);
};
$pdf->SetFillColor(244, 245, 250);
$pdf->SetFont('Helvetica', 'B', 10.5);
$pdf->Cell(0, 7, '  Candidate & Project', 0, 1, 'L', true);
$pdf->Ln(2);
$row('Student', $d['student_name']);
$row('Project Title', $d['title']);
$row('Department', $d['department'] ?: '-');
$row('Reference', $d['reference']);
$row('Defense Date', date('d M Y, H:i', strtotime($d['scheduled_at'])) . ' CAT');
$row('Mode / Venue', ucfirst($d['mode']) . ' / ' . ($d['venue'] ?: '-'));
$pdf->Ln(3);

// ── Examiner scores table ──
$pdf->SetFont('Helvetica', 'B', 10.5);
$pdf->Cell(0, 7, '  Evaluation Breakdown', 0, 1, 'L', true);
$pdf->Ln(2);

$pdf->SetFont('Helvetica', 'B', 8.5);
$pdf->SetFillColor(22, 163, 74);
$pdf->SetTextColor(255, 255, 255);
$w = [54, 27, 22, 20, 24, 22];
$pdf->Cell($w[0], 7, ' Evaluator', 1, 0, 'L', true);
$pdf->Cell($w[1], 7, 'Content/30', 1, 0, 'C', true);
$pdf->Cell($w[2], 7, 'Pres/25', 1, 0, 'C', true);
$pdf->Cell($w[3], 7, 'Orig/25', 1, 0, 'C', true);
$pdf->Cell($w[4], 7, 'Defense/20', 1, 0, 'C', true);
$pdf->Cell($w[5], 7, 'Total', 1, 1, 'C', true);

$pdf->SetTextColor(0, 0, 0);
$pdf->SetFont('Helvetica', '', 9);
$fill = false;
$roleShort = ['supervisor' => 'Supervisor', 'internal_examiner' => 'Internal Examiner', 'external_examiner' => 'External Examiner'];
foreach ($scores as $s) {
    $pdf->SetFillColor(247, 248, 252);
    $name = $s['evaluator_name'] . ' (' . ($roleShort[$s['evaluator_role']] ?? $s['evaluator_role']) . ')';
    $pdf->Cell($w[0], 6.5, ' ' . $name, 1, 0, 'L', $fill);
    $pdf->Cell($w[1], 6.5, rtrim(rtrim(number_format((float)$s['content_quality'], 1), '0'), '.'), 1, 0, 'C', $fill);
    $pdf->Cell($w[2], 6.5, rtrim(rtrim(number_format((float)$s['presentation'], 1), '0'), '.'), 1, 0, 'C', $fill);
    $pdf->Cell($w[3], 6.5, rtrim(rtrim(number_format((float)$s['originality'], 1), '0'), '.'), 1, 0, 'C', $fill);
    $pdf->Cell($w[4], 6.5, rtrim(rtrim(number_format((float)$s['defense_response'], 1), '0'), '.'), 1, 0, 'C', $fill);
    $pdf->SetFont('Helvetica', 'B', 9);
    $pdf->Cell($w[5], 6.5, rtrim(rtrim(number_format((float)$s['total'], 1), '0'), '.'), 1, 1, 'C', $fill);
    $pdf->SetFont('Helvetica', '', 9);
    $fill = !$fill;
}
$pdf->Ln(2);
$pdf->SetFont('Helvetica', 'I', 8);
$pdf->SetTextColor(110, 110, 110);
$pdf->Cell(0, 5, 'Weighting applied: Supervisor 30%  |  Internal Examiners 40%  |  External Examiner 30%.', 0, 1);
$pdf->SetTextColor(0, 0, 0);
$pdf->Ln(2);

// ── Outcome banner ──
$pass = $d['result_status'] === 'pass';
$pdf->SetFillColor($pass ? 34 : 239, $pass ? 197 : 68, $pass ? 94 : 68);
$pdf->SetTextColor(255, 255, 255);
$pdf->SetFont('Helvetica', 'B', 12);
$pdf->Cell(63, 14, '  Aggregate: ' . $d['aggregate_score'] . ' / 100', 0, 0, 'L', true);
$pdf->Cell(64, 14, 'Grade: ' . $d['final_grade'], 0, 0, 'C', true);
$pdf->Cell(63, 14, strtoupper($d['result_status']) . '  ', 0, 1, 'R', true);
$pdf->SetTextColor(0, 0, 0);
$pdf->Ln(12);

// ── Signatures ──
$pdf->SetFont('Helvetica', '', 9);
$y = $pdf->GetY() + 8;
$pdf->Line(20, $y, 85, $y);
$pdf->Line(120, $y, 185, $y);
$pdf->SetXY(20, $y + 1);
$pdf->Cell(65, 5, 'Project Coordinator', 0, 0, 'C');
$pdf->SetXY(120, $y + 1);
$pdf->Cell(65, 5, 'Examination Officer', 0, 1, 'C');

$pdf->Output('D', 'Result_' . $d['reference'] . '.pdf');
audit($db, $id, 'result.exported', "Result sheet PDF generated for {$d['student_name']}");
